#include "server.hpp"

//1.数据库服务器地址
#define HOSTNAME "127.0.0.1"
//2.数据库登录用户名
#define USERNAME "root"
//3.数据库登录密码
#define PASSWORD "123456" 
//4.五子棋项目对应的目标数据库名
#define DBNAME "gobang"
//5.数据库默认服务端口号
#define PORT 3306

int main()
{
    //1.我们首要任务就是创建出“五子棋服务器的对象”也就是class gobang_server这个类的实例化对象
    //这个类中有一个显示的构造函数用来构造对象
    //这个构造函数需要传入“5个参数”，即可完成对五子棋服务器的对象的实例化
    //所以首先我们是现在全局区定义这个参数常量值
    gobang_server _server(HOSTNAME,USERNAME,PASSWORD,DBNAME,PORT);

    //2.第二步骤就是使用“五子棋服务器的对象”调用它的成员函数启动服务器了
    _server.start(8085);
    /*
        8085 就是一个【端口号】，你写 8080、9000、8888 都行！
        它不是固定数字，只是我们选的一个 “空闲号码” 而已！

        1. 端口号到底是什么？
            你可以把服务器想象成 一栋大楼：
            IP 地址（127.0.0.1） = 大楼的地址
            端口号（8085） = 大楼的门牌号
            电脑上有很多软件：QQ、微信、浏览器、你的游戏服务器…它们不能挤在一个门里，必须各走各的门。
            网站默认用 80
            HTTPS 默认用 443
            你的游戏服务器 → 我们自己选一个没人用的 → 8085
        
        2. 为什么偏偏写 8085？
            没有任何特殊含义！
            只是程序员习惯用 8080、8085、9000 这种端口！
            你写成下面这些全都可以正常运行：
                _server.start(8080);  // 可以
                _server.start(9000);  // 可以
                _server.start(8888);  // 可以
                _server.start(1234);  // 可以
                8085 只是我们项目里随便选的一个端口！
    */

    //3.程序正常退出
    return 0;

}